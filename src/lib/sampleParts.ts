const KIND_DIR = { background: "backgrounds", tileset: "tilesets", prop: "props" } as const;

export function partDir(root: string, meta: Pick<PartMeta, "kind" | "id">): string {
  return path.join(root, "parts", KIND_DIR[meta.kind], meta.id);
}

/** Write every sample part (PNG + part.json) plus a credits manifest. */
export async function writeSampleParts(root: string): Promise<PartMeta[]> {
  const defs = sampleDefs();
  for (const def of defs) {
    const dir = partDir(root, def.meta);
    await mkdir(dir, { recursive: true });
    const img = def.draw();
    if (img.width !== def.meta.width || img.height !== def.meta.height) {
      throw new Error(`Sample ${def.meta.id} drew ${img.width}x${img.height}, expected ${def.meta.width}x${def.meta.height}`);
    }
    await writePng(path.join(dir, def.meta.image), img);
    await writeFile(path.join(dir, "part.json"), `${JSON.stringify(def.meta, null, 2)}\n`);
  }
  const manifest = {
    note: "SAMPLE ART — generated procedurally by Easy Scene for demos and tests. Replace with your own art.",
    license: SAMPLE_LICENSE,
    credit: SAMPLE_CREDIT,
    parts: defs.map((d) => ({ id: d.meta.id, kind: d.meta.kind, name: d.meta.name, license: SAMPLE_LICENSE })),
  };
  await writeFile(path.join(root, "parts", "CREDITS.json"), `${JSON.stringify(manifest, null, 2)}\n`);
  await writeFile(
    path.join(root, "parts", "CREDITS.md"),
    `# Sample parts — credits\n\nAll ${defs.length} parts in this folder marked \`"sample": true\` were generated by code in\n\`src/lib/sampleParts.ts\` (seeded noise + shapes). They are original, contain no third-party art,\nand are released under **${SAMPLE_LICENSE}** (public domain dedication).\n\nYour own parts: add \`license\` and \`credit\` fields to each \`part.json\`.\n`,
  );
  return defs.map((d) => d.meta);
}
