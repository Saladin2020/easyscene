"""
Rasterize the short Thai shop-sign words used by the Thai town sample props into
1-bit bitmaps (src/lib/thaiSignText.ts), so the TypeScript art needs no font at runtime.

    python3 scripts/gen-thai-signs.py [path/to/Kanit-Medium.ttf]

Font: Kanit by Cadson Demak (SIL Open Font License 1.1). Only the rendered glyph
bitmaps of these words are stored, not the font itself.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/sand-box/google/Kanit/Kanit-Medium.ttf"
WORDS = [
    ("noodle", "ก๋วยเตี๋ยว", 13),
    ("noodleSmall", "ก๋วยเตี๋ยว", 11),
    ("fruit", "ผลไม้", 11),
    ("mart", "สุขใจมาร์ท", 11),
    ("open24", "24 ชม.", 11),
    ("soi", "ซอย 3", 11),
    ("temple", "วัด", 11),
    ("market", "ตลาด", 11),
    ("coffee", "กาแฟ", 11),
    ("gold", "ร้านทอง", 11),
    ("pharmacy", "ร้านยา", 11),
    ("repair", "ซ่อมรถ", 11),
    ("pier", "ท่าเรือ", 11),
]

out = [
    "/**",
    " * GENERATED by scripts/gen-thai-signs.py — do not edit by hand.",
    " * 1-bit bitmaps of short Thai sign words, rasterized from Kanit (Cadson Demak, SIL OFL 1.1).",
    " * Only these rendered glyph images are stored; no font data ships with Easy Scene.",
    " */",
    "export interface SignText {",
    "  text: string;",
    "  width: number;",
    "  height: number;",
    "  /** rows of '#' (ink) and '.' (empty) */",
    "  rows: string[];",
    "}",
    "",
    "export const THAI_SIGNS = {",
]
for key, text, size in WORDS:
    f = ImageFont.truetype(FONT, size)
    im = Image.new("L", (size * len(text) + 20, size * 3), 0)
    d = ImageDraw.Draw(im)
    d.fontmode = "1"
    d.text((4, size // 2), text, font=f, fill=255)
    bbox = im.getbbox()
    im = im.crop(bbox)
    rows = ["".join("#" if im.getpixel((x, y)) > 127 else "." for x in range(im.width)) for y in range(im.height)]
    out.append(f"  {key}: {{")
    out.append(f"    text: {text!r},".replace("'", '"'))
    out.append(f"    width: {im.width},")
    out.append(f"    height: {im.height},")
    out.append("    rows: [")
    out += [f'      "{r}",' for r in rows]
    out.append("    ],")
    out.append("  },")
out.append("} satisfies Record<string, SignText>;")
out.append("")
out.append("export type ThaiSignKey = keyof typeof THAI_SIGNS;")
open("src/lib/thaiSignText.ts", "w", encoding="utf-8").write("\n".join(out) + "\n")
print("wrote", len(WORDS), "signs")
