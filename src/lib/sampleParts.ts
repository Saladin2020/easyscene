function hills(): RgbaImage {
  const img = createImage(W, H);
  const back = ramp("#79a978", "#88b884", "#9ac690", "#b2d6a2");
  const front = ramp("#457e54", "#56915a", "#6fae6a", "#8cc47a", "#a6d488");
  const backTop = (x: number) => ridge(x, 192, [[3, 14, 2.4], [5, 6, 0.3]], 4, 51);
  const frontTop = (x: number) => ridge(x, 206, [[2, 18, 0.9], [4, 8, 2.2]], 3, 52);
  for (let x = 0; x < W; x++) {
    const t0 = backTop(x);
    for (let y = t0; y < H; y++) {
      const slope = backTop(x + 4) - backTop(x - 4);
      setPx(img, x, y, pick(back, (y === t0 ? 0.95 : 0.55) - slope * 0.05 - (y - t0) * 0.006, x, y, 0.5));
    }
  }
  // distant tree dots and hedgerows on the back hill
  const r = rng(53);
  for (let i = 0; i < 34; i++) {
    const x = Math.floor(r() * W);
    const y = backTop(x) + 2 + Math.floor(r() * 10);
    const rad = 1.5 + r() * 2;
    for (let dy = -3; dy <= 3; dy++) {
      for (let dx = -3; dx <= 3; dx++) {
        if (dx * dx + dy * dy > rad * rad) continue;
        setWrap(img, x + dx, y + dy, dx + dy < -1 ? back[2]! : back[0]!);
      }
    }
  }
  for (let x = 0; x < W; x++) {
    const t0 = frontTop(x);
    for (let y = t0; y < H; y++) {
      const d = y - t0;
      const slope = frontTop(x + 4) - frontTop(x - 4);
      const face = slope < -1 ? 0.12 : slope > 1 ? -0.14 : 0;
      const t = d === 0 ? 1 : d === 1 ? 0.8 : 0.62 + face - d * 0.007 + (vnoise(x, y, 10, 55) - 0.5) * 0.12;
      setPx(img, x, y, pick(front, t, x, y, 0.5));
    }
  }
  return img;
}

/** Layered fir: tiers of drooping, jagged boughs, lit on the left. */
function fir(img: RgbaImage, cx: number, base: number, h: number, pal: Rgb[], seed: number, wrap = true): void {
  const tiers = Math.max(3, Math.round(h / 12));
  const w = Math.max(7, h * 0.46);
  const put = wrap ? setWrap : setPx;
  const owner = new Map<string, number>();
  for (let k = tiers - 1; k >= 0; k--) {
    const yt = base - h + Math.round((k / tiers) * h * 0.82);
    const yb = base - h + Math.round(((k + 1) / tiers) * h * 0.82) + Math.round(h * 0.18 / tiers) + 3;
    const hw = (w / 2) * (0.38 + 0.62 * ((k + 1) / tiers));
    for (let y = yt; y <= yb; y++) {
      const f = (y - yt) / Math.max(1, yb - yt);
      const half = Math.max(0.5, hw * Math.pow(f, 0.85));
      for (let dx = Math.floor(-half); dx <= Math.ceil(half); dx++) {
        const edge = Math.abs(dx) / half;
        if (edge > 1) continue;
        // jagged bough tips along the outer edge and the drooping hem
        if (edge > 0.72 && hash(cx + dx, y, seed) > 0.62) continue;
        if (y === yb && (dx + 64) % 3 !== 0) continue;
        const t = 0.62 - (dx / half) * 0.38 - f * 0.25 + (hash(cx + dx, y, seed + 1) - 0.5) * 0.18;
        owner.set(`${cx + dx},${y}`, k);
        put(img, cx + dx, y, pick(pal, t, wrapX(cx + dx), y, 0.5));
      }
    }
  }
  // the tier above casts a band of shadow onto the top of the tier below
  for (const [key, k] of owner) {
    const [x, y] = key.split(",").map(Number) as [number, number];
    const above = owner.get(`${x},${y - 2}`);
    if (above !== undefined && above < k && owner.get(`${x},${y - 1}`) === k) put(img, x, y, pal[0]!);
  }
  const trunk = ramp("#2a1a14", "#3e2618");
  for (let y = base - 3; y < base + 2; y++) {
    put(img, cx, y, trunk[1]!);
    put(img, cx + 1, y, trunk[0]!);
  }
}

