type Rgb = [number, number, number];
const W = 480;
const H = 270;
/** Sky rows from here down are water (only visible through pits). */
const WATER_Y = 228;

// ---------------- noise + colour helpers ----------------

/** Deterministic integer hash → [0,1). */
function hash(x: number, y: number, seed: number): number {
  let h = (x * 374761393 + y * 668265263 + seed * 2147483647) | 0;
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  return ((h ^ (h >>> 16)) >>> 0) / 4294967296;
}

function rng(seed: number): () => number {
  let s = seed >>> 0;
  return () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const clamp01 = (v: number) => Math.min(1, Math.max(0, v));
const smooth = (t: number) => t * t * (3 - 2 * t);
const wrapX = (x: number, p = W) => ((x % p) + p) % p;

/**
 * Value noise that repeats every `period` px horizontally (period must be a multiple of `cell`),
 * so layers built from it loop seamlessly.
 */
function vnoise(x: number, y: number, cell: number, seed: number, period = W): number {
  const n = Math.max(1, Math.round(period / cell));
  const gx = x / cell;
  const gy = y / cell;
  const x0 = Math.floor(gx);
  const y0 = Math.floor(gy);
  const fx = smooth(gx - x0);
  const fy = smooth(gy - y0);
  const h = (i: number, j: number) => hash(wrapX(i, n), j, seed);
  const a = h(x0, y0) + (h(x0 + 1, y0) - h(x0, y0)) * fx;
  const b = h(x0, y0 + 1) + (h(x0 + 1, y0 + 1) - h(x0, y0 + 1)) * fx;
  return a + (b - a) * fy;
}

const rgb = (hex: string): Rgb => hexToRgb(hex);
const ramp = (...hexes: string[]): Rgb[] => hexes.map(rgb);
const mix = (a: Rgb, b: Rgb, t: number): Rgb => [
  Math.round(a[0] + (b[0] - a[0]) * t),
  Math.round(a[1] + (b[1] - a[1]) * t),
  Math.round(a[2] + (b[2] - a[2]) * t),
];

/** Ordered 4×4 Bayer threshold for crisp gradient dithering. */
const BAYER = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5];
const bayer = (x: number, y: number) => (BAYER[(y & 3) * 4 + (x & 3)]! + 0.5) / 16;

/**
 * Pick a ramp colour for t∈[0,1]. Bands are flat; only the middle `soft` fraction of each
 * band-to-band step is Bayer-dithered (0 = hard bands, 1 = dither the whole step).
 */
function pick(r: Rgb[], t: number, x: number, y: number, soft = 0.5): Rgb {
  const f = clamp01(t) * (r.length - 1);
  const i = Math.min(r.length - 2, Math.floor(f));
  const fr = f - i;
  const u = soft <= 0 ? (fr < 0.5 ? 0 : 1) : clamp01((fr - (0.5 - soft / 2)) / soft);
  return r[u > bayer(x, y) ? i + 1 : i]!;
}

function setPx(img: RgbaImage, x: number, y: number, c: Rgb, a = 255): void {
  if (x < 0 || y < 0 || x >= img.width || y >= img.height) return;
  const i = (y * img.width + x) * 4;
  img.data[i] = c[0];
  img.data[i + 1] = c[1];
  img.data[i + 2] = c[2];
  img.data[i + 3] = a;
}

/** setPx with horizontal wrap — keeps loop layers seamless. */
function setWrap(img: RgbaImage, x: number, y: number, c: Rgb, a = 255): void {
  setPx(img, wrapX(x, img.width), y, c, a);
}

function getPx(img: RgbaImage, x: number, y: number): Rgb {
  const i = (y * img.width + x) * 4;
  return [img.data[i]!, img.data[i + 1]!, img.data[i + 2]!];
}

function alphaAt(img: RgbaImage, x: number, y: number): number {
  if (x < 0 || y < 0 || x >= img.width || y >= img.height) return 0;
  return img.data[(y * img.width + x) * 4 + 3]!;
}

/** Alpha-over one pixel (used for glows and haze). */
function blendPx(img: RgbaImage, x: number, y: number, c: Rgb, a: number): void {
  if (x < 0 || y < 0 || x >= img.width || y >= img.height || a <= 0) return;
  const i = (y * img.width + x) * 4;
  const da = img.data[i + 3]! / 255;
  const sa = Math.min(1, a / 255);
  const oa = sa + da * (1 - sa);
  for (let k = 0; k < 3; k++) img.data[i + k] = Math.round((c[k]! * sa + img.data[i + k]! * da * (1 - sa)) / oa);
  img.data[i + 3] = Math.round(oa * 255);
}

function rect(img: RgbaImage, x0: number, y0: number, w: number, h: number, c: Rgb): void {
  for (let y = y0; y < y0 + h; y++) for (let x = x0; x < x0 + w; x++) setPx(img, x, y, c);
}

/** Copy the opaque pixels of `src` over `dst`. */
function stamp(dst: RgbaImage, src: RgbaImage): void {
  for (let p = 0; p < src.width * src.height; p++) if (src.data[p * 4 + 3]) dst.data.set(src.data.subarray(p * 4, p * 4 + 4), p * 4);
}

/**
 * Selective outline ("sel-out"): every transparent pixel touching the sprite becomes a darkened,
 * cooler copy of the neighbour it touches, instead of flat black.
 */
function selOutline(img: RgbaImage, amount = 0.42, skipBottom = true): void {
  const marks: Array<[number, number, Rgb]> = [];
  for (let y = 0; y < img.height; y++) {
    for (let x = 0; x < img.width; x++) {
      if (alphaAt(img, x, y) !== 0) continue;
      const n: Array<[number, number]> = [[x, y + 1], [x + 1, y], [x - 1, y], [x, y - 1]];
      const hit = n.find(([nx, ny]) => alphaAt(img, nx, ny) === 255);
      if (!hit) continue;
      const c = getPx(img, hit[0], hit[1]);
      marks.push([x, y, [Math.round(c[0] * amount * 0.85), Math.round(c[1] * amount * 0.9), Math.round(c[2] * amount + 10)]]);
    }
  }
  for (const [x, y, c] of marks) if (!(skipBottom && y === img.height - 1)) setPx(img, x, y, c);
}

/** Lambert-ish term for a sphere normal under the shared top-left light. */
function sphereLight(dx: number, dy: number, r: number): number {
  const nx = dx / r;
  const ny = dy / r;
  const nz = Math.sqrt(Math.max(0, 1 - nx * nx - ny * ny));
  return clamp01(0.5 + (-0.55 * nx - 0.65 * ny + 0.52 * nz) * 0.62);
}

// ---------------- skies ----------------

/** Vertical gradient sampled into flat bands, dithered only at the band edges. */
function gradientSky(img: RgbaImage, stops: Array<[number, string]>, bands: number, y1 = WATER_Y): (y: number) => Rgb {
  const cols = stops.map(([t, h]) => [t, rgb(h)] as const);
  const colorAt = (t: number): Rgb => {
    for (let i = 1; i < cols.length; i++) {
      const [t1, c1] = cols[i]!;
      const [t0, c0] = cols[i - 1]!;
      if (t <= t1) return mix(c0, c1, (t - t0) / Math.max(1e-6, t1 - t0));
    }
    return cols[cols.length - 1]![1];
  };
  const palette = Array.from({ length: bands }, (_, i) => colorAt(i / (bands - 1)));
  for (let y = 0; y < y1; y++) {
    for (let x = 0; x < W; x++) setPx(img, x, y, pick(palette, y / (y1 - 1), x, y, 0.6));
  }
  return (y: number) => colorAt(clamp01(y / (y1 - 1)));
}

/** Still water under the horizon: lighter at the surface, ripples of reflected sky. */
function waterBand(img: RgbaImage, water: Rgb[], shimmer: Rgb, seed: number, glints?: { x: number; w: number; c: Rgb }): void {
  for (let y = WATER_Y; y < H; y++) {
    const d = (y - WATER_Y) / (H - WATER_Y);
    for (let x = 0; x < W; x++) {
      const wave = vnoise(x, y * 3, 24, seed) * 0.25;
      setPx(img, x, y, pick(water, 1 - d * 1.1 + wave - 0.12, x, y, 0.5));
    }
  }
  for (let x = 0; x < W; x++) setPx(img, x, WATER_Y, shimmer);
  for (let x = 0; x < W; x++) setPx(img, x, WATER_Y + 1, water[water.length - 1]!);
  for (let y = WATER_Y + 3; y < H - 4; y += 2) {
    const r = rng(seed * 131 + y);
    let x = Math.floor(r() * 30);
    while (x < W) {
      const len = 2 + Math.floor(r() * 6);
      const density = 0.35 * (1 - (y - WATER_Y) / (H - WATER_Y));
      if (r() < density) for (let k = 0; k < len && x + k < W; k++) setPx(img, x + k, y, mix(shimmer, water[water.length - 1]!, 0.35));
      x += len + 6 + Math.floor(r() * 26);
    }
  }
  if (glints) {
    // Pits can open anywhere, so the reflection is spread as sparkles that only thicken under the light source.
    const soft = mix(glints.c, water[water.length - 1]!, 0.45);
    for (let y = WATER_Y + 2; y < H - 1; y += 2) {
      const r = rng(seed * 977 + y);
      let x = Math.floor(r() * 12);
      while (x < W) {
        const len = 1 + Math.floor(r() * 4);
        const dist = Math.min(Math.abs(x - glints.x), W - Math.abs(x - glints.x)) / (glints.w * 2);
        const near = Math.exp(-dist * dist);
        if (r() < 0.1 + 0.6 * near) for (let k = 0; k < len; k++) setWrap(img, x + k, y, near > 0.5 ? glints.c : soft);
        x += len + 3 + Math.floor(r() * 14);
      }
    }
  }
}

interface CloudPalette {
  hi: Rgb;
  base: Rgb;
  shade: Rgb;
  deep: Rgb;
}

/**
 * Cumulus cloud: a row of base puffs with smaller puffs on top, flat bottom,
 * each puff shaded as a sphere so the light reads top-left.
 */
function cloud(img: RgbaImage, cx: number, cy: number, w: number, pal: CloudPalette, seed: number, h = 1): void {
  const r = rng(seed);
  const puffs: Array<[number, number, number]> = [];
  const n = 3 + Math.floor(w / 26);
  for (let i = 0; i < n; i++) {
    const t = (i + 0.5) / n;
    const pr = (w / n) * (0.55 + 0.45 * Math.sin(Math.PI * t)) * h + 2 + r() * 3;
    puffs.push([cx - w / 2 + w * t + (r() - 0.5) * 4, cy - pr * 0.45, pr]);
  }
  const tops = 1 + Math.floor(r() * 2 + w / 60);
  for (let i = 0; i < tops; i++) {
    const t = 0.3 + r() * 0.4;
    const pr = w * (0.16 + r() * 0.08) * h;
    puffs.push([cx - w / 2 + w * t, cy - pr - w * 0.12 * h, pr]);
  }
  const ramp4 = [pal.deep, pal.shade, pal.base, pal.hi];
  const tmp = createImage(img.width, img.height);
  const x0 = Math.floor(cx - w / 2 - w * 0.4);
  const x1 = Math.ceil(cx + w / 2 + w * 0.4);
  const y0 = Math.floor(cy - w * 0.8);
  for (let y = y0; y <= cy; y++) {
    for (let x = x0; x <= x1; x++) {
      let owner = -1;
      for (let i = 0; i < puffs.length; i++) {
        const [px, py, pr] = puffs[i]!;
        if ((x - px) ** 2 + (y - py) ** 2 <= pr * pr) owner = i;
      }
      if (owner < 0) continue;
      const [px, py, pr] = puffs[owner]!;
      // mostly flat body: a lit rim up-left on every puff, shade gathering toward the flat base
      const s = sphereLight(x - px, y - py, pr);
      let t = 0.6 + (s > 0.66 ? 0.32 : s < 0.38 ? -0.22 : 0);
      for (let j = owner + 1; j < puffs.length; j++) {
        const [jx, jy, jr] = puffs[j]!;
        if (Math.hypot(x - (jx + 2), y - (jy + 2)) < jr) t -= 0.25;
      }
      t -= clamp01((y - (cy - 6)) / 6) * 0.5;
      setWrap(tmp, x, y, pick(ramp4, t, wrapX(x, img.width), y, 0.35));
    }
  }
  stamp(img, tmp);
}

/** Long thin stratus streaks (high wisps / sunset bands). */
function streak(img: RgbaImage, cx: number, cy: number, len: number, body: Rgb, rim: Rgb, seed: number): void {
  for (let row = 0; row < 3; row++) {
    const l = len * (1 - row * 0.28);
    const off = (hash(row, 1, seed) - 0.5) * len * 0.3;
    for (let x = Math.round(cx - l / 2 + off); x < cx + l / 2 + off; x++) {
      const y = cy + row;
      setWrap(img, x, y, row === 0 ? rim : body);
    }
  }
}

const DAY_CLOUDS: CloudPalette = { hi: rgb("#ffffff"), base: rgb("#eef5fc"), shade: rgb("#c8d8ee"), deep: rgb("#9fb6d8") };

function skyDay(): RgbaImage {
  const img = createImage(W, H);
  gradientSky(img, [[0, "#2c64b8"], [0.35, "#4a8fd6"], [0.68, "#82bfe8"], [0.88, "#b9e0ef"], [1, "#e4f3ea"]], 9);
  const r = rng(11);
  for (let i = 0; i < 5; i++) streak(img, Math.floor(r() * W), 18 + Math.floor(r() * 40), 30 + r() * 50, rgb("#c4def4"), rgb("#e6f2fb"), i + 3);
  const spots: Array<[number, number, number]> = [[60, 92, 70], [210, 70, 96], [345, 104, 56], [430, 64, 84]];
  for (const [i, [x, y, w]] of spots.entries()) cloud(img, x, y, w, DAY_CLOUDS, 100 + i);
  waterBand(img, ramp("#2a5f92", "#3a7cb0", "#5a9ccc", "#86c2e2"), rgb("#e4f6fb"), 3);
  return img;
}

function skyDusk(): RgbaImage {
  const img = createImage(W, H);
  gradientSky(img, [[0, "#1c1740"], [0.28, "#3f2d6c"], [0.52, "#8c4679"], [0.72, "#d6665e"], [0.88, "#f39a58"], [1, "#ffd585"]], 12);
  // low sun with a dithered halo
  const [sx, sy] = [118, 168];
  const halo = ramp("#f6a05a", "#fbbd6a", "#ffd88a");
  for (let y = sy - 44; y <= sy + 44; y++) {
    for (let x = sx - 44; x <= sx + 44; x++) {
      const d = Math.hypot(x - sx, y - sy);
      if (d > 42 || y >= WATER_Y) continue;
      const t = 1 - d / 42;
      if (t < 0.15) continue;
      const base = getPx(img, wrapX(x), y);
      const c = pick(halo, (t - 0.15) * 1.3, x, y, 0.8);
      if (bayer(x, y) < t * 1.4) setWrap(img, x, y, mix(base, c, 0.65));
    }
  }
  for (let y = sy - 16; y <= sy + 16; y++) {
    for (let x = sx - 16; x <= sx + 16; x++) {
      const d = Math.hypot(x - sx, y - sy);
      if (d <= 15.5) setWrap(img, x, y, d > 13 ? rgb("#ffe59a") : y > sy + 5 ? rgb("#fff0bc") : rgb("#fff8dc"));
    }
  }
  // sunset bands across the sun and sky
  const r = rng(7);
  const bands: Array<[number, number, number]> = [[100, 160, 90], [150, 176, 70], [300, 120, 110], [420, 140, 80], [250, 190, 60], [40, 130, 70]];
  for (const [i, [x, y, l]] of bands.entries()) {
    streak(img, x, y, l, rgb("#b8526e"), rgb("#ff9e78"), 40 + i);
    if (r() > 0.4) streak(img, x + 20, y + 5, l * 0.6, rgb("#9a4468"), rgb("#e67a72"), 60 + i);
  }
  // first stars
  for (let i = 0; i < 46; i++) {
    const x = Math.floor(r() * W);
    const y = Math.floor(r() * 70);
    setPx(img, x, y, r() > 0.75 ? rgb("#ffe9b8") : y < 40 ? rgb("#b8b0e0") : rgb("#8c78b0"));
  }
  waterBand(img, ramp("#2a2048", "#4a2f60", "#87496c", "#d47a6a"), rgb("#ffc890"), 5, { x: sx, w: 30, c: rgb("#ffd99a") });
  return img;
}

function skyNight(): RgbaImage {
  const img = createImage(W, H);
  gradientSky(img, [[0, "#070a1f"], [0.3, "#111a3e"], [0.6, "#1e2c5c"], [0.85, "#2c3a6e"], [1, "#44507e"]], 10);
  // milky way: a dithered band that loops with the layer
  for (let x = 0; x < W; x++) {
    const cy = 70 + 30 * Math.sin((2 * Math.PI * x) / W + 0.6);
    for (let y = Math.floor(cy - 22); y < cy + 22; y++) {
      const t = 1 - Math.abs(y - cy) / 22;
      const n = vnoise(x, y, 8, 21) * 0.7 + vnoise(x, y, 24, 22) * 0.6;
      const v = t * n;
      if (v > 0.55 && bayer(x, y) < (v - 0.55) * 3) setPx(img, x, y, mix(getPx(img, x, y), rgb("#6a76b4"), 0.45));
      else if (v > 0.32 && bayer(x, y) < (v - 0.32) * 1.6) setPx(img, x, y, mix(getPx(img, x, y), rgb("#3c4886"), 0.5));
    }
  }
  const r = rng(77);
  for (let i = 0; i < 240; i++) {
    const x = Math.floor(r() * W);
    const y = Math.floor(r() * (WATER_Y - 30) * Math.sqrt(r()));
    const k = r();
    if (k > 0.97) {
      setPx(img, x, y, rgb("#ffffff"));
      for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]] as const) setWrap(img, x + dx, y + dy, rgb("#9fb0ea"));
    } else setPx(img, x, y, k > 0.8 ? rgb("#fff4d6") : k > 0.45 ? rgb("#a8b6e8") : rgb("#5c6aa6"));
  }
  // crescent moon with a soft halo
  const [mx, my] = [356, 58];
  for (let y = my - 30; y <= my + 30; y++) {
    for (let x = mx - 30; x <= mx + 30; x++) {
      const d = Math.hypot(x - mx, y - my);
      if (d > 13 && d < 28 && bayer(x, y) < (1 - (d - 13) / 15) * 0.55) setPx(img, x, y, mix(getPx(img, x, y), rgb("#5f6fa8"), 0.5));
    }
  }
  for (let y = my - 12; y <= my + 12; y++) {
    for (let x = mx - 12; x <= mx + 12; x++) {
      const d = Math.hypot(x - mx, y - my);
      if (d > 11.5) continue;
      const shadow = Math.hypot(x - (mx + 5), y - (my - 3)) < 10;
      if (shadow) setPx(img, x, y, rgb("#26346a"));
      else setPx(img, x, y, d > 10 ? rgb("#d8dcc0") : hash(x, y, 4) > 0.86 ? rgb("#e6e2c4") : rgb("#fbf6dc"));
    }
  }
  waterBand(img, ramp("#0a1230", "#16224a", "#24346a", "#3c4a82"), rgb("#8090c8"), 9, { x: mx, w: 14, c: rgb("#e8e6c8") });
  return img;
}

function cloudsLayer(): RgbaImage {
  const img = createImage(W, H);
  const pal: CloudPalette = { hi: rgb("#fffdf8"), base: rgb("#fbf4ea"), shade: rgb("#e6d6d0"), deep: rgb("#bfaec0") };
  const hazy: CloudPalette = { hi: rgb("#fbf4ea"), base: rgb("#efe4dc"), shade: rgb("#d9c8c8"), deep: rgb("#bfaec0") };
  const spots: Array<[number, number, number, boolean]> = [
    [40, 60, 78, false], [150, 104, 44, true], [236, 46, 104, false], [330, 112, 50, true], [404, 74, 70, false], [470, 120, 36, true],
  ];
  for (const [i, [x, y, w, far]] of spots.entries()) cloud(img, x, y, w, far ? hazy : pal, 300 + i, far ? 0.8 : 1);
  return img;
}

// ---------------- far / mid / near layers ----------------

/** Ridge heights from sines with integer frequencies + looping noise → seamless every W px. */
function ridge(x: number, base: number, terms: Array<[number, number, number]>, noise = 0, seed = 1): number {
  let y = base;
  for (const [k, amp, phase] of terms) y -= amp * Math.sin((2 * Math.PI * k * x) / W + phase);
  if (noise) y -= (vnoise(x, 0, 12, seed) - 0.5) * noise + (vnoise(x, 0, 4, seed + 1) - 0.5) * noise * 0.3;
  return Math.round(y);
}

function mountainRange(
  img: RgbaImage, top: (x: number) => number, rock: Rgb[], snow: Rgb[], snowLine: number, haze: Rgb, hazeFrom: number, seed: number,
): void {
  for (let x = 0; x < W; x++) {
    const t0 = top(x);
    for (let y = t0; y < H; y++) {
      const d = y - t0;
      // shading follows the slope a few px uphill so faces read as streaked rock, not columns
      const sx = x + Math.round(d * 0.5);
      const slope = top(sx + 4) - top(sx - 4);
      const face = slope < -1.5 ? 0.78 : slope > 1.5 ? 0.22 : 0.5;
      let light = face + (vnoise(x + d * 0.5, y, 8, seed) - 0.5) * 0.22 - d * 0.003;
      if (d === 0) light += 0.3;
      const snowDepth = (snowLine - t0) * 0.7 + (vnoise(x, 0, 6, seed + 3) - 0.5) * 6;
      let c = d < snowDepth ? pick(snow, light + 0.1, x, y, 0.5) : pick(rock, light, x, y, 0.5);
      const hz = clamp01((y - hazeFrom) / 40);
      if (hz > 0 && bayer(x, y) < hz) c = mix(c, haze, 0.35 + hz * 0.3);
      setPx(img, x, y, c);
    }
  }
}

