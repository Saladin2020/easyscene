/**
 * Procedurally generated ORIGINAL sample art (no third-party pixels).
 * Everything here is drawn by code from seeded noise + simple shapes so the
 * workspace works out of the box. Replace with your own Aseprite art any time.
 *
 * Art rules kept across every part:
 * - one light source, top-left: lit faces left/up, shadows right/down
 * - hue-shifted ramps (shadows drift cool, highlights drift warm), each ramp
 *   stays within ±20° of the part's `recolorBase` so hue recolor moves it as one
 * - far layers are paler and hazier (atmospheric perspective), dithered with a
 *   4×4 Bayer matrix only at band transitions so edges stay crisp
 * - every sky ends in a reflective water band: it is hidden under the ground
 *   and only shows through pits
 */
