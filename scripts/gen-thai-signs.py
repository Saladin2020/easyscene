"""
Rasterize the short Thai shop-sign words used by the Thai town sample props into
1-bit bitmaps (src/lib/thaiSignText.ts), so the TypeScript art needs no font at runtime.

    python3 scripts/gen-thai-signs.py [path/to/Kanit-Medium.ttf]

Font: Kanit by Cadson Demak (SIL Open Font License 1.1). Words whose size is a string
("sarabun-px-12") are drawn with that Easy Font pixel font instead (Sarabun Pixel, from
Sarabun by Cadson Demak, SIL OFL 1.1), through the easyfont CLI (EASYFONT_CLI, default
../easyfont-cli.mjs; fonts from EASYFONT_FONTS, default ../easyfont/samples/fonts). Only the
rendered glyph bitmaps of these words are stored, not the fonts themselves.
"""
import os, shutil, subprocess, sys, tempfile
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
EASYFONT_CLI = os.environ.get("EASYFONT_CLI", os.path.join(HERE, "..", "..", "easyfont-cli.mjs"))
EASYFONT_FONTS = os.environ.get("EASYFONT_FONTS", os.path.join(HERE, "..", "..", "easyfont", "samples", "fonts"))

def pixel_font_bitmap(text, font_id):
    """Render with an Easy Font pixel font (1:1 pixels) → cropped L image."""
    ws = tempfile.mkdtemp()
    try:
        os.makedirs(os.path.join(ws, "fonts"))
        for f in os.listdir(EASYFONT_FONTS):
            shutil.copy(os.path.join(EASYFONT_FONTS, f), os.path.join(ws, "fonts", f))
        out = os.path.join(ws, "w.png")
        subprocess.run(["node", EASYFONT_CLI, "render", text, "--font", font_id, "--scale", "1", "--color", "#ffffff", "--bg", "#000000", "--out", out, "--workspace", ws], check=True, capture_output=True)
        im = Image.open(out).convert("L")
        return im.crop(im.point(lambda v: 255 if v > 127 else 0).getbbox())
    finally:
        shutil.rmtree(ws, ignore_errors=True)

FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/sand-box/google/Kanit/Kanit-Medium.ttf"
