function rock(): RgbaImage {
  const img = createImage(24, 14);
  const stone = ramp("#3e3f4c", "#55576a", "#6a6c7c", "#7d7f8c", "#9a9caa", "#bcbec8");
  const moss = ramp("#3d6a40", "#5a8a4e", "#82b060");
  const blobs: Array<[number, number, number, number]> = [[11, 10, 10, 7], [18, 11, 5, 4]];
  for (let y = 1; y < 14; y++) {
    for (let x = 0; x < 24; x++) {
      let owner = -1;
      for (let i = 0; i < blobs.length; i++) {
        const [cx, cy, rx, ry] = blobs[i]!;
        if (((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2 <= 1) owner = i;
      }
      if (owner < 0) continue;
      const [cx, cy, rx, ry] = blobs[owner]!;
      // quantised normals give chiselled facets
      const nx = Math.round(((x - cx) / rx) * 3) / 3;
      const ny = Math.round(((y - cy) / ry) * 3) / 3;
      let t = sphereLight(nx * 10, ny * 10, 10) * 1.3 - 0.45 + (hash(x, y, 13) - 0.5) * 0.1;
      if (owner === 0 && blobs[1] && ((x - 17.5) / 5) ** 2 + ((y - 9.5) / 4) ** 2 <= 1.2 && x < 15) t -= 0.25;
      setPx(img, x, y, pick(stone, t, x, y, 0.4));
      if (owner === 0 && ny < -0.6 && nx < 0.35 && vnoise(x, y, 2, 14) > 0.35) setPx(img, x, y, pick(moss, 0.55 - nx * 0.5, x, y, 0.3));
    }
  }
  for (const [x, y] of [[13, 7], [14, 8], [14, 9], [15, 10]] as const) setPx(img, x, y, stone[0]!);
  for (let x = 0; x < 24; x++) setPx(img, x, 13, alphaAt(img, x, 13) ? stone[0]! : [0, 0, 0]);
  for (let x = 0; x < 24; x++) if (!alphaAt(img, x, 12)) setPx(img, x, 13, [0, 0, 0], 0);
  selOutline(img);
  tuft(img, 1, 4);
  tuft(img, 20, 23);
  return img;
}

