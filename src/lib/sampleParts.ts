function fillPx(p: TilePalette, x: number, y: number, seed: number, stone: boolean): Rgb {
  if (stone) {
    // brick-ish courses
    const row = Math.floor(y / 8);
    const off = row % 2 ? 4 : 0;
    if (y % 8 === 7 || (x + off) % 8 === 7) return p.fillDark;
    if (y % 8 === 0 && (x + off) % 8 < 6) return p.fillLight;
    return p.fill;
  }
  const n = hash(x, y, seed);
  return n > 0.93 ? p.fillLight : n < 0.08 ? p.fillDark : p.fill;
}

function drawTerrainTile(img: RgbaImage, ox: number, oy: number, mask: number, p: TilePalette, stone: boolean): void {
  const s = 16;
  for (let y = 0; y < s; y++) for (let x = 0; x < s; x++) setPx(img, ox + x, oy + y, fillPx(p, x, y, 1, stone));
  if (!(mask & MASK_N)) {
    for (let x = 0; x < s; x++) {
      const blade = hash(x, 0, 9) > 0.5 ? 1 : 0;
      setPx(img, ox + x, oy, p.topHi);
      setPx(img, ox + x, oy + 1, p.top);
      setPx(img, ox + x, oy + 2, p.top);
      setPx(img, ox + x, oy + 3, blade ? p.topDark : p.top);
      if (blade && x % 3 === 0) setPx(img, ox + x, oy + 4, p.topDark);
    }
  }
  if (!(mask & MASK_W)) for (let y = 0; y < s; y++) setPx(img, ox, oy + y, p.edge);
  if (!(mask & MASK_E)) for (let y = 0; y < s; y++) setPx(img, ox + s - 1, oy + y, p.edge);
  if (!(mask & MASK_S)) {
    for (let x = 0; x < s; x++) {
      setPx(img, ox + x, oy + s - 1, p.edge);
      setPx(img, ox + x, oy + s - 2, p.fillDark);
    }
  }
}

function drawPlatform(img: RgbaImage, ox: number, oy: number, left: boolean, right: boolean, p: TilePalette): void {
  for (let x = 0; x < 16; x++) {
    setPx(img, ox + x, oy, p.edge);
    setPx(img, ox + x, oy + 1, p.plankHi);
    setPx(img, ox + x, oy + 2, x % 8 === 7 ? p.plankDark : p.plank);
    setPx(img, ox + x, oy + 3, x % 8 === 7 ? p.plankDark : p.plank);
    setPx(img, ox + x, oy + 4, p.plankDark);
    setPx(img, ox + x, oy + 5, p.edge);
  }
  // little brackets under the plank
  for (const bx of [3, 12]) for (let y = 6; y < 9 - Math.abs(bx - 8) / 4; y++) setPx(img, ox + bx, oy + y, p.plankDark);
  if (left) for (let y = 0; y < 6; y++) setPx(img, ox, oy + y, p.edge);
  if (right) for (let y = 0; y < 6; y++) setPx(img, ox + 15, oy + y, p.edge);
}

function drawSlope(img: RgbaImage, ox: number, oy: number, risesRight: boolean, p: TilePalette, stone: boolean): void {
  for (let y = 0; y < 16; y++) {
    for (let x = 0; x < 16; x++) {
      const lx = risesRight ? x : 15 - x;
      const d = lx + y - 15; // 0 on the diagonal
      if (d < 0) continue;
      const c = d === 0 ? p.topHi : d < 3 ? p.top : d === 3 ? p.topDark : fillPx(p, x, y, 1, stone);
      setPx(img, ox + x, oy + y, c);
    }
  }
}

function tileset(p: TilePalette, stone: boolean): RgbaImage {
  const img = createImage(ATLAS_COLUMNS * 16, ATLAS_ROWS * 16);
  for (let m = 0; m < 16; m++) drawTerrainTile(img, (m % 4) * 16, Math.floor(m / 4) * 16, m, p, stone);
  drawPlatform(img, 0, 64, true, true, p);
  drawPlatform(img, 16, 64, true, false, p);
  drawPlatform(img, 32, 64, false, false, p);
  drawPlatform(img, 48, 64, false, true, p);
  drawSlope(img, 0, 80, true, p, stone);
  drawSlope(img, 16, 80, false, p, stone);
  return img;
}

