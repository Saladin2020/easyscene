/** Ridge heights from sines with integer frequencies → seamless every W px. */
function ridge(x: number, base: number, terms: Array<[number, number, number]>): number {
  let y = base;
  for (const [k, amp, phase] of terms) y -= amp * Math.sin((2 * Math.PI * k * x) / W + phase);
  return Math.round(y);
}

