/** Deterministic integer hash → [0,1). */
function hash(x: number, y: number, seed: number): number {
  let h = (x * 374761393 + y * 668265263 + seed * 2147483647) | 0;
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  return ((h ^ (h >>> 16)) >>> 0) / 4294967296;
}

function rng(seed: number): () => number {
  let s = seed >>> 0;
  return () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rgb = (hex: string): Rgb => hexToRgb(hex);
const mix = (a: Rgb, b: Rgb, t: number): Rgb => [
  Math.round(a[0] + (b[0] - a[0]) * t),
  Math.round(a[1] + (b[1] - a[1]) * t),
  Math.round(a[2] + (b[2] - a[2]) * t),
];

function setPx(img: RgbaImage, x: number, y: number, c: Rgb, a = 255): void {
  if (x < 0 || y < 0 || x >= img.width || y >= img.height) return;
  const i = (y * img.width + x) * 4;
  img.data[i] = c[0];
  img.data[i + 1] = c[1];
  img.data[i + 2] = c[2];
  img.data[i + 3] = a;
}

/** setPx with horizontal wrap — keeps loop layers seamless. */
function setWrap(img: RgbaImage, x: number, y: number, c: Rgb, a = 255): void {
  setPx(img, ((x % img.width) + img.width) % img.width, y, c, a);
}

function alphaAt(img: RgbaImage, x: number, y: number): number {
  if (x < 0 || y < 0 || x >= img.width || y >= img.height) return 0;
  return img.data[(y * img.width + x) * 4 + 3]!;
}

/** 1px outline around opaque pixels. */
function outline(img: RgbaImage, c: Rgb): void {
  const marks: Array<[number, number]> = [];
  for (let y = 0; y < img.height; y++) {
    for (let x = 0; x < img.width; x++) {
      if (alphaAt(img, x, y) !== 0) continue;
      if (alphaAt(img, x - 1, y) || alphaAt(img, x + 1, y) || alphaAt(img, x, y - 1) || alphaAt(img, x, y + 1)) marks.push([x, y]);
    }
  }
  for (const [x, y] of marks) setPx(img, x, y, c);
}

function disc(img: RgbaImage, cx: number, cy: number, r: number, c: Rgb, wrap = false): void {
  for (let y = Math.floor(cy - r); y <= Math.ceil(cy + r); y++) {
    for (let x = Math.floor(cx - r); x <= Math.ceil(cx + r); x++) {
      if ((x - cx) ** 2 + (y - cy) ** 2 <= r * r) (wrap ? setWrap : setPx)(img, x, y, c);
    }
  }
}

/** Ordered 4×4 Bayer threshold for crisp gradient dithering. */
const BAYER = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5];
const bayer = (x: number, y: number) => (BAYER[(y & 3) * 4 + (x & 3)]! + 0.5) / 16;

function gradientSky(stops: Array<[number, string]>, steps = 7): RgbaImage {
  const img = createImage(W, H);
  const cols = stops.map(([t, h]) => [t, rgb(h)] as const);
  const colorAt = (t: number): Rgb => {
    for (let i = 1; i < cols.length; i++) {
      const [t1, c1] = cols[i]!;
      const [t0, c0] = cols[i - 1]!;
      if (t <= t1) return mix(c0, c1, (t - t0) / Math.max(1e-6, t1 - t0));
    }
    return cols[cols.length - 1]![1];
  };
  for (let y = 0; y < H; y++) {
    const t = y / (H - 1);
    const band = t * steps;
    for (let x = 0; x < W; x++) {
      const q = Math.floor(band) + (band - Math.floor(band) > bayer(x, y) ? 1 : 0);
      setPx(img, x, y, colorAt(Math.min(1, q / steps)));
    }
  }
  return img;
}

/** Draw one cloud on its own scratch layer, then copy its opaque pixels (so clouds never cut each other). */
function cloud(img: RgbaImage, cx: number, cy: number, w: number, light: Rgb, shade: Rgb): void {
  const tmp = createImage(img.width, img.height);
  cloudShape(tmp, cx, cy, w, light, shade);
  for (let p = 0; p < tmp.width * tmp.height; p++) if (tmp.data[p * 4 + 3]) img.data.set(tmp.data.subarray(p * 4, p * 4 + 4), p * 4);
}

function cloudShape(img: RgbaImage, cx: number, cy: number, w: number, light: Rgb, shade: Rgb): void {
  const r = rng(cx * 7 + cy);
  const puffs = 3 + Math.floor(r() * 3);
  const discs: Array<[number, number, number]> = [];
  for (let i = 0; i < puffs; i++) {
    const t = (i + 0.5) / puffs;
    const px = cx - w / 2 + w * t;
    // taller in the middle, flat-ish bottom
    const pr = 4 + (w / puffs) * (0.45 + 0.35 * Math.sin(Math.PI * t)) + r() * 2;
    discs.push([px, cy - pr * 0.5, pr]);
  }
  for (const [x, y, rad] of discs) disc(img, x, y + 2, rad, shade, true);
  for (const [x, y, rad] of discs) disc(img, x, y, rad, light, true);
  // flatten the base
  for (let x = Math.floor(cx - w / 2 - 6); x < cx + w / 2 + 6; x++) {
    for (let y = Math.floor(cy) + 2; y < cy + 14; y++) setWrap(img, x, y, [0, 0, 0], 0);
  }
}

