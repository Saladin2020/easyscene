function pine(img: RgbaImage, cx: number, base: number, h: number, c: Rgb, hi: Rgb): void {
  const w = Math.max(6, Math.floor(h * 0.45));
  for (let y = 0; y < h; y++) {
    const tier = (y % Math.max(4, Math.floor(h / 4))) / Math.max(4, Math.floor(h / 4));
    const half = Math.round(((y + 2) / h) * (w / 2) * (0.6 + tier * 0.4));
    for (let dx = -half; dx <= half; dx++) setWrap(img, cx + dx, base - h + y, dx < -half + 2 ? hi : c);
  }
  for (let y = base - 3; y < base + 2; y++) setWrap(img, cx, y, rgb("#3a2618"));
}

